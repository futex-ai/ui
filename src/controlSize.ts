/**
 * The size scale shared by the library's interactive controls — the
 * {@link Button} and the {@link Input} / {@link InputFrame} text fields — so a
 * form can size its buttons and inputs from a single vocabulary. `md` is the
 * default everywhere; `sm` is the compact density used in dense rows and
 * toolbars, and `lg` is the roomier density for primary calls to action and
 * touch-first layouts.
 */
export type ControlSize = "sm" | "md" | "lg";
